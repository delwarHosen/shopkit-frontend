type Seed = {
  slug: string;
  name: string;
  brand: string;
  categoryId: string;
  price: number;
  comparePrice?: number;
  options: ProductOption[];
  rating: number;
  reviewCount: number;
  stock: number;
  sold: number;
  featured?: boolean;
  daysAgo: number;
  tags?: string[];
};

function mk(s: Seed): Product {
  return {
    id: `p-${s.slug}`,
    slug: s.slug,
    name: s.name,
    brand: s.brand,
    description: `${s.name}, ${s.brand} ব্র্যান্ডের উন্নত মানের পণ্য। দৈনন্দিন ব্যবহার ও বিশেষ অনুষ্ঠান, দুটোর জন্যই মানানসই। প্রতিটি পণ্য পাঠানোর আগে মান যাচাই করা হয়।`,
    highlights: highlightsByCategory[s.categoryId] ?? [],
    price: s.price,
    comparePrice: s.comparePrice,
    images: [1, 2, 3].map(
      (n) => `https://picsum.photos/seed/${s.slug}-${n}/800/1000`,
    ),
    categoryId: s.categoryId,
    tags: s.tags ?? [],
    options: s.options,
    rating: s.rating,
    reviewCount: s.reviewCount,
    stock: s.stock,
    sold: s.sold,
    featured: s.featured ?? false,
    isNew: s.daysAgo <= 14,
    createdAt: new Date(BASE - s.daysAgo * DAY).toISOString(),
  };
}

